const noIncidents = (lastReviewed: string): ReviewedEventPreview["safety"] => ({
  assessment: "No safety incident identified in the reviewed source set",
  incidentCount: 0,
  highestClassification: "None identified",
  injuriesAndDeathsStatus: "No verified injuries or deaths identified",
  propertyDamageStatus: "No verified property damage identified",
  summary:
    "The reviewed sources did not identify a safety incident. This is not a finding that no incident occurred.",
  lastReviewed,
});

const leadByRef = new Map(twelveMonthVerificationLeads.map((lead) => [lead.ref, lead]));

export const publishedVerificationEventAdditions = configs.map((config) => {
  const lead = leadByRef.get(config.ref);
  if (!lead) throw new Error(`Missing verification lead ${config.ref}.`);
  const sources: EventPublicSource[] = [
    {
      publisher: lead.primarySource.publisher,
      headline: lead.title,
      url: lead.primarySource.url,
      publicationDate: null,
      sourceType: "News report",
      sourceRole: "Lead",
    },
    ...(config.extraSources ?? []),
  ];
  const evidenceNote = config.evidenceNote ?? lead.evidenceNote;
  return {
    internalId: config.internalId,
    slug: config.slug,
    title: lead.title,
    eventType: config.eventType,
    eventStatus: config.eventStatus,
    primaryTopic: config.primaryTopic,
    topic: lead.title,
    stateOrUnionTerritory: lead.state,
    publicLocation: config.publicLocation,
    startDate: config.startDate,
    endDate: config.endDate,
    lastConfirmedActive: config.endDate ?? config.startDate,
    lastReviewed: "2026-08-05",
    summary: evidenceNote,
    directedAt: config.directedAt,
    eventVerification: "Occurrence and public description reviewed against the cited sources",
    publicationStatus: "published" as const,
    publicLaunchStatus: "launchable" as const,
    publishedAt: "2026-08-05",
    approvedSourceCount: sources.length,
    sources,
    safety: noIncidents("2026-08-05"),
    safetyIncidents: [],
    visual: {
      kind: "no_approved_event_media" as const,
      evidenceClass: "no_approved_event_media" as const,
      title: lead.title,
      location: config.publicLocation,
      dateOrStatus: config.eventStatus,
      sourceCount: sources.length,
      sourceHref: lead.primarySource.url,
    },
  };
}) satisfies readonly ReviewedEventPreview[];

